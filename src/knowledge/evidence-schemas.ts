import { z } from "zod/v4";
import { EvidenceRefSchema } from "../domain/evidence.js";
import { KnowledgeDocumentInputSchema, KnowledgeSourceSchema } from "./schemas.js";

export const EvidenceModelDestinationSchema = z.enum(["local", "configured_chat_gateway"]);
export type EvidenceModelDestination = z.infer<typeof EvidenceModelDestinationSchema>;

export const KnowledgeEvidenceSourceSchema = KnowledgeSourceSchema.extend({
  /** Explicitly reviewed destinations for model processing. Missing values default to local-only. */
  allowedModelDestinations: z.array(EvidenceModelDestinationSchema).min(1).default(["local"]),
});
export type KnowledgeEvidenceSource = z.infer<typeof KnowledgeEvidenceSourceSchema>;

export const KnowledgeEvidenceSectionSchema = z.object({
  id: z.string().trim().min(1).max(180),
  heading: z.string().trim().max(500).nullable().default(null),
  kind: z.enum(["paragraph", "list_item", "table"]),
  text: z.string().trim().min(1).max(200_000),
  locator: z.string().trim().max(500).nullable().default(null),
});
export type KnowledgeEvidenceSection = z.infer<typeof KnowledgeEvidenceSectionSchema>;

export const KnowledgeEvidenceTypeSchema = z.enum(["methodology", "external_report", "historical_player_analysis", "first_party_observation"]);
export type KnowledgeEvidenceType = z.infer<typeof KnowledgeEvidenceTypeSchema>;

export const KnowledgeEvidenceDocumentMetadataSchema = KnowledgeDocumentInputSchema.omit({ content: true }).extend({
  evidenceType: KnowledgeEvidenceTypeSchema.optional(),
  sampleSummary: z.string().trim().max(2_000).nullable().default(null),
  observedFrom: z.iso.date().nullable().default(null),
  observedTo: z.iso.date().nullable().default(null),
  normalizationVersion: z.string().trim().min(1).max(120).default("raw-sections-v1"),
  sourcePayloadSha256: z.string().regex(/^[a-f0-9]{64}$/u).nullable().default(null),
});
export type KnowledgeEvidenceDocumentMetadata = z.infer<typeof KnowledgeEvidenceDocumentMetadataSchema>;

export const KnowledgeEvidenceDocumentInputSchema = KnowledgeEvidenceDocumentMetadataSchema.extend({
  content: KnowledgeDocumentInputSchema.shape.content,
  sections: z.array(KnowledgeEvidenceSectionSchema).min(1).max(20_000).optional(),
}).superRefine((input, context) => {
  if (input.observedFrom && input.observedTo && input.observedFrom > input.observedTo) {
    context.addIssue({ code: "custom", path: ["observedTo"], message: "资料样本的结束日期不能早于开始日期。" });
  }
  if (input.corpus === "player_report" && input.entityIds.length === 0) {
    context.addIssue({ code: "custom", path: ["entityIds"], message: "球员定性资料必须关联一个可寻址的主体标识；无主体 ID 的第一方观察保留在本地，不进入球员检索索引。" });
  }
  if (input.corpus === "methodology" && input.evidenceType && input.evidenceType !== "methodology") {
    context.addIssue({ code: "custom", path: ["evidenceType"], message: "方法语料的资料类别必须标为 methodology。" });
  }
  if (input.corpus === "player_report" && input.evidenceType === "methodology") {
    context.addIssue({ code: "custom", path: ["evidenceType"], message: "方法资料不能归入球员报告语料。" });
  }
  if (input.sections && input.sections.map((section) => section.text).join("\n\n").trim() !== input.content.trim()) {
    context.addIssue({ code: "custom", path: ["sections"], message: "结构化片段必须逐字覆盖规范化正文，不能隐去或改写来源内容。" });
  }
});
export type KnowledgeEvidenceDocumentInput = z.infer<typeof KnowledgeEvidenceDocumentInputSchema>;

export const EvidencePlayerSubjectSchema = z.object({
  subjectId: z.string().trim().min(3).max(200),
  displayName: z.string().trim().min(2).max(120),
  aliases: z.array(z.string().trim().min(2).max(120)).max(20).default([]),
});
export type EvidencePlayerSubject = z.infer<typeof EvidencePlayerSubjectSchema>;

export const EvidenceRetrievalRequestSchema = z.discriminatedUnion("kind", [
  z.object({
    kind: z.literal("methodology"),
    query: z.string().trim().min(2).max(2_000),
    limit: z.number().int().min(1).max(6).default(6),
  }),
  z.object({
    kind: z.literal("player_report"),
    query: z.string().trim().min(2).max(2_000),
    subjects: z.array(EvidencePlayerSubjectSchema).min(1).max(10),
    sampleFrom: z.iso.date().optional(),
    sampleTo: z.iso.date().optional(),
    sampleSeasons: z.array(z.string().trim().min(2).max(40)).max(5).optional(),
    limit: z.number().int().min(1).max(12).default(6),
    perSubjectLimit: z.number().int().min(1).max(2).default(2),
  }).superRefine((request, context) => {
    if (request.sampleFrom && request.sampleTo && request.sampleFrom > request.sampleTo) {
      context.addIssue({ code: "custom", path: ["sampleTo"], message: "查询样本范围的结束日期不能早于开始日期。" });
    }
    if (new Set(request.subjects.map(({ subjectId }) => subjectId)).size !== request.subjects.length) {
      context.addIssue({ code: "custom", path: ["subjects"], message: "每个已核验主体在一次检索中只能出现一次。" });
    }
  }),
]);
export type EvidenceRetrievalRequest = z.infer<typeof EvidenceRetrievalRequestSchema>;

export const EvidenceAccessContextSchema = z.object({
  /** Generated by the server for one user-input turn. It never comes from the model. */
  turnId: z.string().trim().min(8).max(200),
  /** Stable owner across retrieval, gap planning, follow-up, and a final source check. */
  investigationId: z.string().trim().min(8).max(200).optional(),
  rankingRound: z.union([z.literal(1), z.literal(2)]).optional(),
  purpose: z.enum(["recruitment", "reporting", "evaluation"]),
  modelDestination: EvidenceModelDestinationSchema,
  /** Evaluation-only retrieval ablation; normal Agent requests always use the configured retrieval strategy. */
  retrievalMode: z.enum(["hybrid", "full_text", "dense_vector"]).optional(),
}).superRefine((context, validation) => {
  if (context.retrievalMode && context.purpose !== "evaluation") {
    validation.addIssue({ code: "custom", path: ["retrievalMode"], message: "Pure retrieval ablations are evaluation-only." });
  }
});
export type EvidenceAccessContext = z.infer<typeof EvidenceAccessContextSchema>;

const EvidenceSourceAttributionSchema = z.object({
  sourceId: z.string(),
  sourceName: z.string(),
  title: z.string(),
  url: z.string().url(),
  author: z.string(),
  publisher: z.string(),
  publishedAt: z.string().nullable(),
  license: z.string(),
  attribution: z.string(),
  corpus: z.enum(["methodology", "player_report"]),
  displayAllowed: z.boolean(),
  sourceType: KnowledgeEvidenceTypeSchema,
  subjects: z.array(EvidencePlayerSubjectSchema),
  competition: z.string().nullable(),
  season: z.string().nullable(),
  observedFrom: z.iso.date().nullable(),
  observedTo: z.iso.date().nullable(),
  sampleSummary: z.string().nullable(),
  sectionPath: z.array(z.string()),
});

export const KnowledgeEvidenceItemSchema = z.object({
  ref: EvidenceRefSchema,
  text: z.string().min(1),
  source: EvidenceSourceAttributionSchema,
  rank: z.number().int().positive(),
  rankMode: z.enum(["hybrid", "full_text", "dense_vector", "gateway_reranked", "local_cross_encoder", "hybrid_degraded"]),
});
export type KnowledgeEvidenceItem = z.infer<typeof KnowledgeEvidenceItemSchema>;

export const EvidenceSubjectCoverageSchema = z.object({
  subjectId: z.string(),
  status: z.enum(["found", "not_covered", "no_relevant_evidence", "not_processed_due_to_limit"]),
});
export type EvidenceSubjectCoverage = z.infer<typeof EvidenceSubjectCoverageSchema>;

export const KnowledgeEvidenceBundleSchema = z.object({
  status: z.enum(["not_triggered", "found", "not_covered", "no_relevant_evidence", "unavailable"]),
  evidence: z.array(KnowledgeEvidenceItemSchema),
  subjectCoverage: z.array(EvidenceSubjectCoverageSchema),
  generationId: z.string().nullable(),
  traceId: z.string().uuid(),
  failureCode: z.enum(["budget_exhausted", "model_unavailable", "index_unavailable", "reference_invalid", "source_revoked", "identity_unavailable", "sample_scope_unavailable", "query_too_long", "investigation_unknown"]).nullable(),
  rankingMode: z.enum(["hybrid", "full_text", "dense_vector", "gateway_reranked", "local_cross_encoder", "hybrid_degraded"]).nullable(),
  rankingDurationMs: z.number().nonnegative().nullable(),
  rankingInputTokens: z.number().int().nonnegative().nullable(),
  rankingOutputTokens: z.number().int().nonnegative().nullable(),
  rankingGatewayAttempts: z.number().int().nonnegative().default(0),
  subqueryCount: z.number().int().nonnegative().default(0),
  unavailableSubqueryCount: z.number().int().nonnegative().default(0),
  zeroHitSubqueryCount: z.number().int().nonnegative().default(0),
  notCoveredSubqueryCount: z.number().int().nonnegative().default(0),
  blockedSubqueryCount: z.number().int().nonnegative().default(0),
  candidateCount: z.number().int().nonnegative(),
  budgetMsUsed: z.number().int().nonnegative(),
  budgetMsRemaining: z.number().int().nonnegative(),
});
export type KnowledgeEvidenceBundle = z.infer<typeof KnowledgeEvidenceBundleSchema>;
